package io.github.knaitoe.theoldesthouse.labyrinth;

import io.github.knaitoe.theoldesthouse.TheOldestHouse;
import java.util.*;
import java.util.function.Predicate;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.server.level.ServerPlayer;
import net.neoforged.bus.api.SubscribeEvent;
import net.neoforged.fml.common.EventBusSubscriber;
import net.neoforged.neoforge.event.entity.living.AnimalTameEvent;
import net.neoforged.neoforge.event.entity.player.PlayerEvent;
import net.neoforged.neoforge.event.tick.ServerTickEvent;

/**
 * 0.4.165 (owner: "can you work on an advancement panel next?"): the two tabs of docs/ADVANCEMENTS_DESIGN.md, generated by
 * tools/generate_advancements.py. Every advancement but chalk and the spool has an impossible criterion; the House awards it
 * here from what the save already records about this reader, on login, every two seconds while they play, and at once when
 * a story resolves. So a reader's menu always shows their own history, an old save included, and nothing is awarded for
 * anything the save does not hold. Nothing announces to chat or pays a reward. The quiet rooms and the House's read are
 * never advancements.
 */
@EventBusSubscriber(modid=TheOldestHouse.MOD_ID)
public final class HouseAdvancements {
    private HouseAdvancements(){}
    /** The account tab's progress steps, in the order the design gives them. */
    static final int FIVE=5,TWENTY=20;

    /** Awards one advancement's remaining criteria; true if it was newly completed. */
    static boolean award(ServerPlayer p,String tab,String id){
        var holder=p.server.getAdvancements().get(ResourceLocation.fromNamespaceAndPath(TheOldestHouse.MOD_ID,tab+"/"+id));
        if(holder==null)return false;
        var progress=p.getAdvancements().getOrStartProgress(holder);if(progress.isDone())return false;
        boolean done=false;for(String criterion:progress.getRemainingCriteria())done|=p.getAdvancements().award(holder,criterion);
        return done;
    }
    /** A journey moment the save never kept, awarded where it happens; the advancement is then its record. Spectators earn nothing. */
    public static void earn(ServerPlayer p,String id){if(!p.isSpectator()&&p.server.getAdvancements()!=null)award(p,"house",id);}
    public static boolean has(ServerPlayer p,String tab,String id){
        var holder=p.server.getAdvancements().get(ResourceLocation.fromNamespaceAndPath(TheOldestHouse.MOD_ID,tab+"/"+id));
        return holder!=null&&p.getAdvancements().getOrStartProgress(holder).isDone();
    }

    /** Everything this reader's save already shows, awarded once. */
    public static void sync(ServerPlayer p){
        if(p.server.getAdvancements()==null)return;
        var data=LabyrinthData.get(p.server);var id=p.getUUID();
        for(var step:HouseFacts.JOURNEY)if(step.test().test(p))award(p,"house",step.id());
        // The account: the stories, their kinds and the way toward the Witness.
        int count=WitnessAccount.count(data,id);var kinds=new HashSet<String>();
        for(var story:WitnessAccount.Story.values())if(WitnessAccount.has(data,id,story)){award(p,"account",story.id);award(p,"account","kind_"+story.kind);kinds.add(story.kind);}
        if(count>0||HouseFacts.holdsAccount(p))award(p,"account","account");
        if(count>=1)award(p,"account","first_story");
        if(kinds.size()>=2)award(p,"account","two_kinds");
        if(count>=FIVE)award(p,"account","five_stories");
        if(count>=TWENTY)award(p,"account","twenty_stories");
        if(WitnessAccount.ready(data,id))award(p,"account","enough");
        if(count>=WitnessAccount.Story.values().length)award(p,"account","every_story");
    }
    @SubscribeEvent public static void login(PlayerEvent.PlayerLoggedInEvent e){if(e.getEntity() instanceof ServerPlayer p)sync(p);}
    /** The bone and fish ways of taming a House stray (feeding it meat is LabyrinthEncounters.feedStray). */
    @SubscribeEvent public static void tamed(AnimalTameEvent e){if(e.getTamer() instanceof ServerPlayer p&&e.getAnimal().getTags().contains(LabyrinthEncounters.STRAY))earn(p,"stray");}
    @SubscribeEvent public static void tick(ServerTickEvent.Post e){
        if(e.getServer().getTickCount()%40!=17)return;
        for(var p:e.getServer().getPlayerList().getPlayers())if(!p.isSpectator())sync(p);
    }
    /** A journey advancement and the saved fact that earns it. */
    record Step(String id,Predicate<ServerPlayer> test){}
}
