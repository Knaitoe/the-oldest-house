"""Original timber/grain sounds and a muffled father's three rehearsed lives. No monster cues."""
import argparse
import array
import hashlib
import json
import math
import os
from pathlib import Path
import random
import subprocess
import tempfile
import wave

ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'src/main/resources/assets/the_oldest_house/sounds/silo'
RATE=22050
WORDS=('She took a bus to Tucson.','She met a boy with a flatbed.',"She's just waiting out the winter.")
VOICES=('radio_tucson','radio_flatbed','radio_winter')


def wood(kind):
    rng=random.Random(135+len(kind));duration={'groan':1.8,'splinter':1.1,'grain':.65}[kind];out=[];low=0
    for i in range(int(RATE*duration)):
        t=i/RATE;q=t/duration;noise=rng.uniform(-1,1);low=.86*low+.14*noise
        if kind=='groan':
            envelope=math.sin(math.pi*q)**1.2
            creak=math.sin(2*math.pi*(72*t+13*t*t))*.2+math.sin(2*math.pi*143*t)*.06
            value=(creak+low*.34)*(0.4+.6*abs(math.sin(t*21)))*envelope
        elif kind=='splinter':
            value=(noise*.32+low*.4)*math.exp(-t*5)
            for when in (.035,.13,.29):
                if t>=when:value+=noise*.28*math.exp(-(t-when)*45)
        else:value=(noise*.16+low*.25)*(math.sin(math.pi*q)**2)
        out.append(value)
    return out


def speech(engine, text, folder):
    path=folder/'speech.wav'
    subprocess.run([engine,'-v','en-us+m2','-s','125','-p','29','-a','80','-w',str(path),text],check=True,stdout=subprocess.DEVNULL)
    with wave.open(str(path),'rb') as f:
        assert f.getnchannels()==1 and f.getsampwidth()==2 and f.getframerate()==RATE
        raw=array.array('h',f.readframes(f.getnframes()));samples=[v/32768 for v in raw]
    # A restricted radio band, imperfect loudspeaker, and the same room's short reflections.
    out=[0.0]*int(.32*RATE);low=0;baseline=0;rng=random.Random(135)
    for x in samples:
        baseline+=.055*(x-baseline);low+=.37*((x-baseline)-low)
        out.append(math.tanh(low*1.8)*.07+rng.uniform(-.0022,.0022))
    out.extend([0.0]*int(.35*RATE))
    dry=out[:]
    for delay, gain in ((.085,.16),(.16,.08),(.26,.045)):
        shift=int(delay*RATE)
        for i in range(shift,len(out)):out[i]+=dry[i-shift]*gain
    fade=int(.08*RATE)
    for i in range(fade):out[i]*=i/fade;out[-i-1]*=i/fade
    return out


def encode(name,samples,folder):
    pcm=array.array('h',(int(max(-.95,min(.95,x))*32767) for x in samples));path=folder/(name+'.wav')
    with wave.open(str(path),'wb') as f:f.setnchannels(1);f.setsampwidth(2);f.setframerate(RATE);f.writeframes(pcm.tobytes())
    target=OUT/(name+'.ogg')
    subprocess.run(['ffmpeg','-v','error','-y','-i',str(path),'-c:a','libvorbis','-q:a','4',str(target)],check=True)
    return {'samples':len(samples),'rate':RATE,'ticks':math.ceil(len(samples)/RATE*20),'sha256':hashlib.sha256(target.read_bytes()).hexdigest()}


def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');p.add_argument('--espeak',default=os.environ.get('SILO_ESPEAK','espeak-ng'));args=p.parse_args()
    manifest=ROOT/'art/silo_audio135.json'
    if args.check:
        data=json.loads(manifest.read_text())
        for name, info in data['sounds'].items():
            target=OUT/(name+'.ogg');assert hashlib.sha256(target.read_bytes()).hexdigest()==info['sha256'],f'Changed silo audio {name}'
            decoded=subprocess.check_output(['ffmpeg','-v','error','-i',str(target),'-f','f32le','-ac','1','-ar',str(RATE),'-'])
            values=array.array('f',decoded);assert values and max(abs(v) for v in values)<.96,f'Clipped silo audio {name}'
        assert tuple(data['words'])==WORDS
    else:
        OUT.mkdir(parents=True,exist_ok=True);data={'words':WORDS,'sounds':{}}
        with tempfile.TemporaryDirectory() as d:
            temp=Path(d)
            for name in ('groan','splinter','grain'):data['sounds'][name]=encode(name,wood(name),temp)
            for name, text in zip(VOICES,WORDS):data['sounds'][name]=encode(name,speech(args.espeak,text,temp),temp)
        manifest.parent.mkdir(parents=True,exist_ok=True);manifest.write_text(json.dumps(data,indent=2)+'\n')
        java=ROOT/'src/main/java/io/github/knaitoe/theoldesthouse/labyrinth/SiloAudio.java'
        ticks=','.join(str(data['sounds'][name]['ticks']) for name in VOICES)
        java.write_text('package io.github.knaitoe.theoldesthouse.labyrinth;\n\n/** Actual complete native cue durations, generated by tools/generate_silo_audio.py. */\nfinal class SiloAudio {\n    static final int[] TICKS={'+ticks+'};\n    private SiloAudio(){}\n}\n')
    print('Six original mono silo cues decode without clipping; actual sentence durations drive timber decay.')


if __name__=='__main__':main()
